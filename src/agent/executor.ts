/**
 * Generates simulated output for mock steps.
 */
function getSimulatedOutput(step: PlanStep, task: string): string {
  switch (step.serviceType) {
    case "search":
      return `[SIMULATED SEARCH] Located mock ecosystem documentation and active developer registries for "${task}".`;
    case "report":
      return `[SIMULATED REPORT] Formatted findings into structured digest ready for user consumption.`;
    default:
      return `[SIMULATED GENERAL] Processed task step "${step.title}" successfully.`;
  }
}

/**
 * Executes a TaskPlan sequentially.
 * - Step 2 calls the real DefiLlama research service.
 * - Step 3 obtains the HTTP 402 payment challenge (via live unpaid probe to the gateway or explicit test payload), verifies policy compliance (cap <= 0.01 USDC, Celo mainnet, official USDC contract), and requests explicit user approval.
 * - If approved, constructs a valid Cencori inference request.
 * - Live payment execution is disabled by default unless options.enablePaidExecution === true (or ENABLE_PAID_EXECUTION=true).
 * - Step 4 synthesizes the final report incorporating the AI Market & Liquidity Assessment if available, or DefiLlama metrics alone if payment is declined or skipped.
 *
 * @param plan The TaskPlan generated by createPlan
 * @param askApproval Callback function to request yes/no approval from the user
 * @param options Execution configuration options
 * @returns An ExecutionResult with details for each step
 */
export async function executePlan(
  plan: TaskPlan,
  askApproval?: ApprovalCallback,
  options?: ExecutionOptions
): Promise<ExecutionResult> {
  if (!plan || !plan.steps || plan.steps.length === 0) {
    return {
      task: plan?.task || "",
      status: "failed",
      completedSteps: 0,
      totalSteps: 0,
      results: [],
      summary: "Execution failed: No actionable plan steps were provided.",
    };
  }

  const results: StepExecutionResult[] = [];
  let realResearchData: RealResearchResult | null = null;
  let paidServiceApproved = false;
  let validatedQuote: ValidatedQuote | null = null;
  let aiAssessmentContent: string | null = null;

  console.log("\n==========================================");
  console.log("       TaskPilot AI — Task Execution       ");
  console.log("==========================================");
  console.log(`Executing ${plan.totalSteps} planned steps for: "${plan.task}"\n`);

  for (const step of plan.steps) {
    try {
      console.log(`▶ Running Step ${step.stepNumber}/${plan.totalSteps}: [${step.title}]`);

      // STEP 2: Real external research service (DefiLlama)
      if (step.serviceType === "data") {
        console.log(`  Mode   : [REAL EXTERNAL SERVICE]`);
        console.log(`  Source : DefiLlama Public API (https://api.llama.fi/protocols)`);
        console.log(`  Action : Fetching live Celo DeFi protocol statistics...`);

        const fetchResearch = options?.researchFn ?? fetchCeloDefiProjects;
        const research = await fetchResearch(8000);
        realResearchData = research;

        if (research.success && research.protocols.length > 0) {
          const output = `[REAL DATA - DefiLlama API]\n      ${research.summary}`;

          results.push({
            stepNumber: step.stepNumber,
            title: step.title,
            serviceType: step.serviceType,
            status: "completed",
            isRealService: true,
            serviceSource: research.sourceUrl,
            output,
          });

          console.log(`  ✔ Status: Completed with real external data`);
          console.log(`  Output:\n      ${research.summary}\n`);
        } else {
          const failureReason = research.error || "No active protocols returned";
          results.push({
            stepNumber: step.stepNumber,
            title: step.title,
            serviceType: step.serviceType,
            status: "failed",
            isRealService: true,
            serviceSource: research.sourceUrl,
            output: `[REAL SERVICE FAILED] ${failureReason}`,
          });

          console.log(`  ✖ Status: Real service call failed: ${failureReason}\n`);
        }
      }

      // STEP 3: Paid Service Quote Validation & User Approval Gate
      else if (step.serviceType === "analysis") {
        console.log(`  Mode   : [PAID SERVICE QUOTE & USER APPROVAL]`);
        console.log(`  Action : Obtaining x402 payment challenge for external analysis...`);

        let rawChallenge: unknown;

        if (options?.challengePayload !== undefined) {
          // Explicitly provided for offline test suites
          rawChallenge = options.challengePayload;
        } else {
          // Live probe: Query the gateway dynamically with an unpaid request
          console.log(`  Action : Sending unpaid probe to Cencori gateway (${CENCORI_ENDPOINT})...`);
          const probeFn = options?.fetchLiveChallengeFn ?? fetchLiveCencoriChallenge;
          const liveProbe = await probeFn();

          if (!liveProbe.success || !liveProbe.challenge) {
            const probeError = liveProbe.error || "Failed to retrieve live HTTP 402 challenge from gateway";
            console.log(`  ✖ Status: Live unpaid probe failed (${probeError})`);
            console.log(`  [Notice] Skipping paid service. Falling back to DefiLlama report.\n`);

            results.push({
              stepNumber: step.stepNumber,
              title: step.title,
              serviceType: step.serviceType,
              status: "completed",
              isRealService: false,
              serviceSource: CENCORI_ENDPOINT,
              output: `[LIVE PROBE FAILED] ${probeError}. Paid request skipped; no funds spent.`,
            });
            continue;
          }

          rawChallenge = liveProbe.challenge;
        }

        // Validate the untrusted 402 challenge envelope
        const validation = validateX402Challenge(rawChallenge);

        if (!validation.isValid) {
          console.log(`  ✖ Status: Quote validation failed (${validation.reason})`);
          results.push({
            stepNumber: step.stepNumber,
            title: step.title,
            serviceType: step.serviceType,
            status: "failed",
            isRealService: false,
            output: `[INVALID QUOTE REJECTED] ${validation.reason}`,
          });
          continue;
        }

        // Policy compliance verification (network: celo, token: USDC, recipient match, cap <= 10000 atomic units)
        const compliance = validateCencoriQuote(validation);
        if (!compliance.isCompliant) {
          const reason = compliance.reason || "Quote violates security policy";
          console.log(`  ✖ Status: Quote rejected by security policy (${reason})`);
          results.push({
            stepNumber: step.stepNumber,
            title: step.title,
            serviceType: step.serviceType,
            status: "failed",
            isRealService: false,
            output: `[QUOTE REJECTED BY SAFETY POLICY] ${reason}`,
          });
          continue;
        }

        validatedQuote = validation;

        console.log(`\n  ----------------------------------------`);
        console.log(`  [x402 Payment Challenge Validated]`);
        console.log(formatQuoteSummary(validatedQuote));
        console.log(`  ----------------------------------------`);

        // Request explicit user approval
        let approved = false;
        if (askApproval) {
          try {
            const promptText = `\n  Do you authorize TaskPilot to spend ${validatedQuote.humanAmount} ${validatedQuote.tokenSymbol} for this service? [y/N]: `;
            approved = await askApproval(promptText);
          } catch {
            approved = false;
          }
        }

        if (approved) {
          paidServiceApproved = true;
          console.log(`  ✔ Status: User Approved`);

          const protocols = realResearchData?.success ? realResearchData.protocols : [];
          const cencoriRequest = buildCencoriRequestBody(protocols, plan.task);

          console.log(`  ----------------------------------------`);
          console.log(`  [Cencori Inference Request Prepared]`);
          console.log(`  Endpoint   : ${CENCORI_ENDPOINT}`);
          console.log(`  Model      : ${cencoriRequest.model}`);
          console.log(`  Max Tokens : ${cencoriRequest.max_tokens}`);
          console.log(`  Prompt     : "${cencoriRequest.messages[0].content}"`);
          console.log(`  ----------------------------------------`);

          let execResult: CencoriExecutionResult;
          if (options?.executorFn) {
            execResult = await options.executorFn(cencoriRequest);
          } else {
            execResult = await executeCencoriInference(cencoriRequest, {
              enablePaidExecution: options?.enablePaidExecution,
              accountName: options?.accountName,
            });
          }

          if (execResult.success && execResult.parsedResponse?.success) {
            aiAssessmentContent = execResult.parsedResponse.content;
            console.log(`  ✔ Status: Inference completed successfully`);
            console.log(`  Assessment: ${aiAssessmentContent}\n`);

            results.push({
              stepNumber: step.stepNumber,
              title: step.title,
              serviceType: step.serviceType,
              status: "completed",
              isRealService: true,
              serviceSource: validatedQuote.resource,
              output: `[PAID INFERENCE COMPLETED] Received AI assessment from Cencori x402 gateway: "${aiAssessmentContent}"`,
            });
          } else if (execResult.isExecuted) {
            console.log(`  ✖ Status: Inference execution failed (${execResult.error})\n`);
            results.push({
              stepNumber: step.stepNumber,
              title: step.title,
              serviceType: step.serviceType,
              status: "failed",
              isRealService: true,
              serviceSource: validatedQuote.resource,
              output: `[PAID INFERENCE FAILED] ${execResult.error}`,
            });
          } else {
            console.log(
              `  Note: Spend authorized (${validatedQuote.humanAmount} ${validatedQuote.tokenSymbol}). Live payment execution is disabled by default (no transaction signed or sent).\n`
            );
            results.push({
              stepNumber: step.stepNumber,
              title: step.title,
              serviceType: step.serviceType,
              status: "completed",
              isRealService: true,
              serviceSource: validatedQuote.resource,
              output: `[APPROVAL GRANTED & REQUEST PREPARED] Authorized spend of ${validatedQuote.humanAmount} ${validatedQuote.tokenSymbol} for ${validatedQuote.description}. Built request body for model ${cencoriRequest.model} with ${cencoriRequest.max_tokens} max tokens. Paid gateway invocation disabled by default.`,
            });
          }
        } else {
          paidServiceApproved = false;
          console.log(`  [Notice] User declined or skipped payment.`);
          console.log(`  ✔ Status: Payment safely bypassed. No request sent, no funds spent.\n`);

          results.push({
            stepNumber: step.stepNumber,
            title: step.title,
            serviceType: step.serviceType,
            status: "completed",
            isRealService: false,
            output: `[PAYMENT CANCELLED BY USER] User declined authorization. Paid request was not sent.`,
          });
        }
      }

      // OTHER STEPS: Simulated / Local
      else {
        console.log(`  Mode   : [SIMULATED STEP - No external API called]`);
        console.log(`  Action : ${step.description}`);

        let simulatedText = getSimulatedOutput(step, plan.task);

        if (step.serviceType === "report" && realResearchData?.success) {
          const defiMetricsSummary = `Based on real data from DefiLlama, the top Celo DeFi projects by TVL are: ${realResearchData.protocols
            .map((p) => `${p.name} ($${p.celoTvlUsd.toLocaleString()})`)
            .join(", ")}.`;

          if (aiAssessmentContent) {
            simulatedText = `[SYNTHESIZED REPORT]\n      ${defiMetricsSummary}\n\n      ### AI Market & Liquidity Assessment (Cencori x402)\n      ${aiAssessmentContent}`;
          } else if (paidServiceApproved) {
            simulatedText = `[SYNTHESIZED REPORT]\n      ${defiMetricsSummary}\n      Paid Service Status: Authorized & Prepared for Cencori AI Inference (${validatedQuote?.humanAmount} ${validatedQuote?.tokenSymbol}, model: ${CENCORI_MODEL}). Live payment safely disabled by default.`;
          } else {
            simulatedText = `[SYNTHESIZED REPORT]\n      ${defiMetricsSummary}\n      Paid Service Status: Skipped (no funds spent).`;
          }
        }

        results.push({
          stepNumber: step.stepNumber,
          title: step.title,
          serviceType: step.serviceType,
          status: "completed",
          isRealService: false,
          output: simulatedText,
        });

        console.log(`  ✔ Status: Completed (Simulated)`);
        console.log(`  Output:\n      ${simulatedText}\n`);
      }
    } catch (stepError: unknown) {
      const errorMessage = stepError instanceof Error ? stepError.message : String(stepError);
      console.log(`  ✖ Status: Failed (${errorMessage})\n`);

      results.push({
        stepNumber: step.stepNumber,
        title: step.title,
        serviceType: step.serviceType,
        status: "failed",
        isRealService: false,
        output: `[ERROR] Step failed: ${errorMessage}`,
      });
    }
  }

  const completedCount = results.filter((r) => r.status === "completed").length;
  const executionStatus =
    completedCount === plan.totalSteps ? "success" : completedCount > 0 ? "partial" : "failed";

  const summary = `Task execution ${executionStatus}: ${completedCount} of ${plan.totalSteps} steps completed safely.`;

  return {
    task: plan.task,
    status: executionStatus,
    completedSteps: completedCount,
    totalSteps: plan.totalSteps,
    results,
    summary,
  };
}
